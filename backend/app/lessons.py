def feedback(metrics, rules=None):
    """Explain observations against user-selected rules without inventing advice."""
    result = []
    for code, rule in (rules or {}).items():
        value = metrics.get(code)
        if value is None:
            result.append(
                {
                    "metric": code,
                    "level": "missing",
                    "message": f"{LABELS.get(code, code)}: ข้อมูลไม่พอ ตรวจภาพ กล้องและช่วงบันทึกแล้วทดลองใหม่",
                }
            )
        elif ("min" in rule and value < rule["min"]) or ("max" in rule and value > rule["max"]):
            result.append(
                {
                    "metric": code,
                    "level": "review",
                    "message": f"{LABELS.get(code, code)}อยู่นอกเกณฑ์รุ่นนี้ ทบทวนการเคลื่อนไหวและตำแหน่งกล้องก่อนฝึกซ้ำ",
                }
            )
        else:
            result.append(
                {
                    "metric": code,
                    "level": "within",
                    "message": f"{LABELS.get(code, code)}อยู่ในเกณฑ์รุ่นนี้",
                }
            )
    if not rules:
        result.append(
            {"metric": None, "level": "info", "message": "ยังไม่มีเกณฑ์ยืนยัน ใช้ทบทวนค่าที่วัดได้เท่านั้น"}
        )
    if metrics.get("follow_through") is not None or metrics.get("center_aim_error") is not None:
        result.append(
            {
                "metric": None,
                "level": "info",
                "message": "ค่าการส่งคิวใช้ marker และเวลาลูกเริ่มเคลื่อนเป็นตัวแทน ไม่ใช่การตรวจจุดสัมผัสจริงบนลูกน้ำเงิน",
            }
        )
    return result
